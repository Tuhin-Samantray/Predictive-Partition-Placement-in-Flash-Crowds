"""Render the generated configs/tuned_ext.yaml from the P4a tuning summary (A29).

Same tagged format as tuned.yaml, kept in a separate file so the hashed tuned.yaml is never rewritten.
P4a uses the forecaster chosen for P4 (A13) and the same exhaustive grid as P4.
"""

TAG = "[design]"


def render_tuned_ext(summaries, datasets):
    out = ["# generated by scripts/render_tuned_ext.py from the P4a tuning-split summaries; never hand-edited"]
    out.append("tuned_ext:")
    for ds in datasets:
        match = [s for s in summaries if s["dataset"] == ds and s["policy"] == "P4a"]
        if len(match) != 1:
            raise ValueError("need exactly one P4a summary for " + ds)
        s = match[0]
        why = "%s tuned on the tuning split, mean damage %.6g over %d replicates, %d of %d configs" % (
            TAG, s["best_mean_damage"], s["n_replicates"], s["n_configs"], s["grid_size"])
        out.append("  %s:" % ds)
        out.append("    P4a:")
        out.append("      forecaster: %s # %s same forecaster as P4 (A13, A29)" % (s["forecaster"], TAG))
        for key in sorted(s["best_params"]):
            out.append("      %s: %r # %s" % (key, s["best_params"][key], why))
    return "\n".join(out) + "\n"
