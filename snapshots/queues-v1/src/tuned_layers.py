"""Render the generated configs/tuned_layers.yaml from the layers-on tuning summaries (A32).

Same tagged format as tuned.yaml, kept in a separate file so tuned.yaml and tuned_ext.yaml are never rewritten.
P3 and P6 use the forecaster chosen for P4 (A13); all four policies are tuned under the same cross-layer
conditions (A30 item 4).
"""

TAG = "[design]"
NAMES = ("P1", "P3", "P5", "P6")
FORECASTED = ("P3", "P6")


def render_tuned_layers(summaries, datasets):
    out = ["# generated by scripts/render_tuned_layers.py from the layers-on tuning-split summaries; never hand-edited"]
    out.append("tuned_layers:")
    for ds in datasets:
        out.append("  %s:" % ds)
        for name in NAMES:
            match = [s for s in summaries if s["dataset"] == ds and s["policy"] == name]
            if len(match) != 1:
                raise ValueError("need exactly one %s summary for %s" % (name, ds))
            s = match[0]
            why = "%s tuned on the tuning split with the cross-layer model on (%s, h_net %s, phi %s), mean damage %.6g over %d replicates, %d of %d configs" % (
                TAG, s["mode"], s["h_net"], s["phi"], s["best_mean_damage"], s["n_replicates"], s["n_configs"],
                s["grid_size"])
            out.append("    %s:" % name)
            if name in FORECASTED:
                out.append("      forecaster: %s # %s same forecaster as P4 (A13, A30)" % (s["forecaster"], TAG))
            for key in sorted(s["best_params"]):
                out.append("      %s: %r # %s" % (key, s["best_params"][key], why))
    return "\n".join(out) + "\n"
