"""Render the generated configs/tuned.yaml from tuning summaries (never hand-edited).

Every leaf carries a comment with a tag and its justification (G1). The best tuned reactive
policy is chosen per dataset as the lower tuning-split mean damage of P1 and P2, ties to the
fewer moves, then to P1; it is decided here, before any grid run.
"""

REACTIVE = ("P1", "P2")
TAG = "[design]"


def label_of(summary):
    if summary["policy"] == "P3":
        return "P3_" + summary["forecaster"]
    return summary["policy"]


def best_reactive(summaries, dataset):
    cands = [s for s in summaries if s["dataset"] == dataset and s["policy"] in REACTIVE]
    if len(cands) != len(REACTIVE):
        raise ValueError("need P1 and P2 summaries for " + dataset)
    cands.sort(key=lambda s: (s["best_mean_damage"], s["best_mean_moves"], s["policy"]))
    return cands[0], cands[1]


def order_key(summary):
    names = ("P1", "P2", "P3", "P4", "P5")
    return (names.index(summary["policy"]), summary.get("forecaster") or "")


def render_tuned(summaries, datasets):
    out = ["# generated by scripts/03_tune.py from the tuning-split summaries; never hand-edited"]
    out.append("best_reactive:")
    for ds in datasets:
        best, other = best_reactive(summaries, ds)
        out.append("  %s: %s # %s lower tuning-split mean damage %.6g than %s %.6g on %s"
                   % (ds, best["policy"], TAG, best["best_mean_damage"], other["policy"],
                      other["best_mean_damage"], ds))
    out.append("tuned:")
    for ds in datasets:
        out.append("  %s:" % ds)
        for s in sorted((x for x in summaries if x["dataset"] == ds), key=order_key):
            out.append("    %s:" % label_of(s))
            why = "%s tuned on the tuning split, mean damage %.6g over %d replicates, %d of %d configs" % (
                TAG, s["best_mean_damage"], s["n_replicates"], s["n_configs"], s["grid_size"])
            if s["policy"] == "P4":
                out.append("      forecaster: %s # %s lowest tuning-split MASE (A13)" % (s["forecaster"], TAG))
            for key in sorted(s["best_params"]):
                out.append("      %s: %r # %s" % (key, s["best_params"][key], why))
    return "\n".join(out) + "\n"
